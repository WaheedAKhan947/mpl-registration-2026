import mongoose from "mongoose";
import { EXTRA_TYPES, WICKET_TYPES } from "@/lib/scoring";

const objectId = mongoose.Schema.Types.ObjectId;

const WicketSchema = new mongoose.Schema(
  {
    type: { type: String, enum: WICKET_TYPES, required: true },
    playerOut: { type: objectId, ref: "Registration", required: true },
    fielders: [{ type: objectId, ref: "Registration" }],
  },
  { _id: false }
);

// One document per delivery (or scoring event: penalty runs, retirement).
// Balls are the source of truth for every score and stat on the site; see
// lib/scoring.js for how `extraRuns`, `boundary` and `wicket` are read.
const BallSchema = new mongoose.Schema(
  {
    match: { type: objectId, ref: "Match", required: true },
    innings: { type: Number, required: true, min: 1, max: 4 },
    // Order within the innings, gapless while scoring. Corrections replace a
    // ball in place, so seq never needs renumbering.
    seq: { type: Number, required: true, min: 1 },

    // Denormalised from the replay so commentary can be listed without
    // replaying; rewritten whenever an earlier ball is corrected.
    over: { type: Number, default: 0 },
    ballInOver: { type: Number, default: 0 },
    legal: { type: Boolean, default: true },
    freeHit: { type: Boolean, default: false },

    striker: { type: objectId, ref: "Registration", default: null },
    nonStriker: { type: objectId, ref: "Registration", default: null },
    bowler: { type: objectId, ref: "Registration", default: null },
    bowlerChange: { type: Boolean, default: false },

    runsOffBat: { type: Number, min: 0, max: 7, default: 0 },
    extrasType: { type: String, enum: [...EXTRA_TYPES, null], default: null },
    // All extras on this ball, including the wide / no-ball penalty run.
    extraRuns: { type: Number, min: 0, max: 10, default: 0 },
    boundary: { type: Number, enum: [4, 6, null], default: null },
    wicket: { type: WicketSchema, default: null },

    commentary: { type: String, trim: true, default: "" },

    // Generated by the scorer's device, so a retried request (bad network)
    // finds the ball it already wrote instead of adding a second one.
    clientId: { type: String, required: true, trim: true },
    createdBy: { type: objectId, ref: "AdminUser", default: null },
  },
  { timestamps: true }
);

BallSchema.index({ match: 1, innings: 1, seq: 1 }, { unique: true });
BallSchema.index({ clientId: 1 }, { unique: true });
BallSchema.index({ bowler: 1 });

// In development Next.js keeps a model compiled from an older version of
// this file across hot reloads, and Mongoose then silently drops any field
// added since. Re-register it so schema edits apply without a restart.
if (process.env.NODE_ENV !== "production" && mongoose.models.Ball) {
  mongoose.deleteModel("Ball");
}

export default mongoose.models.Ball || mongoose.model("Ball", BallSchema);
